import type { SourceModule } from '../sources/types';

/** The part of a source module the index needs. */
export type LicenseEntry = Pick<SourceModule, 'id' | 'meta'>;

/** Wording in `meta.license` that marks a source without an explicit data licence. */
const NO_EXPLICIT_LICENSE = /no explicit|unclear|cited|no licen[cs]e/i;

/** True when the licence text says the data has no explicit licence (e.g. "No explicit data licence …", "terms unclear"). */
export function lacksExplicitLicense(license: string): boolean {
  return NO_EXPLICIT_LICENSE.test(license);
}

/** One markdown table cell: single line, pipes escaped. */
function cell(text: string): string {
  return text.replace(/\s*[\r\n]+\s*/g, ' ').replace(/\|/g, '\\|').trim();
}

/**
 * The text of pipeline/raw/LICENSES.md: what the raw files are, which sources have no explicit data licence, and a
 * table of every source module (id, name, licence, credit, url) taken from its `meta`.
 * Deterministic (no timestamp), so regenerating it every week does not change the file unless a source changed.
 */
export function licenseIndex(modules: LicenseEntry[]): string {
  const unclear = modules.filter((m) => lacksExplicitLicense(m.meta.license));
  const lines: string[] = [
    '# Raw data sources and licences',
    '',
    'The files in this directory are normalised extracts of the public sources listed below (model, date, score or count),',
    'kept so that the site data can be rebuilt offline (recomputation) without refetching. They are not copies of the upstream',
    'files. Each source stays under its own licence and terms; the credit line is what the site shows for it.',
    '',
    'This file is generated by `npm run fetch` from the `meta` of every module in `src/sources` (see `src/raw/licenses.ts`); do not edit it by hand.',
    '',
    '## Sources without an explicit data licence',
    '',
  ];
  if (unclear.length) {
    lines.push('Their data is published openly but states no data licence of its own (or the terms are unclear); it is cited and credited, not relicensed.', '');
    for (const m of unclear) lines.push(`- \`${m.id}\` (${cell(m.meta.name)}): ${cell(m.meta.license)}`);
  } else {
    lines.push('None.');
  }
  lines.push('', '## All sources', '', '| id | name | licence | credit | url |', '| --- | --- | --- | --- | --- |');
  for (const m of modules) {
    lines.push(`| \`${m.id}\` | ${cell(m.meta.name)} | ${cell(m.meta.license)} | ${cell(m.meta.credit)} | ${cell(m.meta.url)} |`);
  }
  return lines.join('\n') + '\n';
}
